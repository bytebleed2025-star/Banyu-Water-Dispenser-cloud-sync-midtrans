param(
  [string]$EspIp = "",
  [int]$Port = 3000,
  [string]$AdminKeyword = "banyu123",
  [switch]$NoStart
)

# Recipe A - laptop only. Starts banyu/server.js (kiosk + local dashboard).
# No cloud, no MongoDB: orders stay in banyu/data/db.json.
# Works with the current Hydronode ESP32 firmware (HTTP API); no firmware change.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$serverDir = Join-Path $root "banyu"
$settingsPath = Join-Path $serverDir "settings.env"

if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  throw "Node.js 18+ is required: https://nodejs.org (check 'node --version')."
}

function Normalize-Base([string]$v) {
  $v = ($v -as [string]).Trim()
  if (-not $v) { return "" }
  if ($v -notmatch '^https?://') { $v = "http://" + $v }
  return $v.TrimEnd('/')
}

$esp = Normalize-Base $EspIp

if (-not (Test-Path $settingsPath)) {
  $lines = @(
    "# Generated by trial/start-recipe-a.ps1 - edit and restart to change.",
    "# Midtrans: fill MIDTRANS_SERVER_KEY and set MIDTRANS_ENV=sandbox for test money.",
    "PAYMENT_MODE=mock",
    "MIDTRANS_SERVER_KEY=",
    "MIDTRANS_ENV=sandbox",
    "MIDTRANS_PAYMENTS=",
    "",
    "# Current Hydronode ESP32 (HTTP API). Empty = demo mode (the tablet fakes the pour).",
    "ESP32_BASE_URL=$esp",
    "",
    "# Local dashboard login keyword (change this).",
    "ADMIN_KEYWORDS=$AdminKeyword",
    "",
    "# Recipe A: no cloud copy. Leave these empty.",
    "CLOUD_URL=",
    "SYNC_SECRET=",
    "MACHINE_ID=banyu-kiosk-01"
  )
  Set-Content -Path $settingsPath -Value $lines -Encoding ASCII
  Write-Host "Created $settingsPath" -ForegroundColor Green
} else {
  Write-Host "Using existing $settingsPath (not overwritten)." -ForegroundColor Yellow
}

$conf = @{}
Get-Content $settingsPath | ForEach-Object {
  if ($_ -match '^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$') { $conf[$matches[1]] = $matches[2] }
}
$payment = if ($conf['PAYMENT_MODE']) { $conf['PAYMENT_MODE'] } else { 'mock' }
$espShown = if ($conf['ESP32_BASE_URL']) { $conf['ESP32_BASE_URL'] } else { '(empty - demo mode)' }
$keyword = if ($conf['ADMIN_KEYWORDS']) { $conf['ADMIN_KEYWORDS'].Split(',')[0].Trim() } else { 'banyu-admin' }
$cloud = if ($conf['CLOUD_URL']) { $conf['CLOUD_URL'] } else { '(off - Recipe A)' }

$kioskUrl = "http://localhost:$Port/"
$dashUrl = "http://localhost:$Port/dashboard.html"
$lan = @(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
  Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' } |
  Select-Object -ExpandProperty IPAddress -Unique)

Write-Host ""
Write-Host "Banyu kiosk - Recipe A (laptop only)" -ForegroundColor Cyan
Write-Host "  Payment mode : $payment"
Write-Host "  Dispenser    : $espShown"
Write-Host "  Cloud copy   : $cloud"
Write-Host "  Dashboard key: $keyword"
Write-Host ""
Write-Host "  Kiosk     : $kioskUrl"
Write-Host "  Dashboard : $dashUrl"
if ($lan.Count -gt 0) {
  Write-Host "  Tablet    : http://$($lan[0]):$Port/   (same Wi-Fi)"
  if ($lan.Count -gt 1) { Write-Host "              other addresses: $($lan -join ', ')" }
}
Write-Host ""
Write-Host "MIDTRANS: mock = demo button on the payment screen. For sandbox, put the" -ForegroundColor DarkGray
Write-Host "          server key in settings.env, set MIDTRANS_ENV=sandbox, restart." -ForegroundColor DarkGray
Write-Host "ESP:      run trial/check-esp.ps1 -EspIp <esp-ip> to test it first." -ForegroundColor DarkGray
Write-Host "Firewall: allow TCP $Port if the tablet cannot connect (needs admin):" -ForegroundColor DarkGray
Write-Host "          netsh advfirewall firewall add rule name=`"Banyu Kiosk $Port`" dir=in action=allow protocol=TCP localport=$Port" -ForegroundColor DarkGray
Write-Host ""

if ($NoStart) {
  Write-Host "NoStart: settings checked, server not started." -ForegroundColor Yellow
  exit 0
}

$browserJob = Start-Job -ScriptBlock {
  param($u)
  Start-Sleep -Seconds 3
  Start-Process $u
} -ArgumentList $kioskUrl

Push-Location $serverDir
try {
  node server.js
} finally {
  Pop-Location
  Remove-Job $browserJob -Force -ErrorAction SilentlyContinue
}
