param(
  [string]$EspIp = "",
  [int]$CloudPort = 4000,
  [int]$KioskPort = 3000,
  [string]$MongoUri = "",
  [string]$CloudUrl = "",
  [switch]$NoStart
)

# Recipe B - laptop + cloud copy.
#   Window 1: banyu/server.js        (kiosk + local dashboard, talks to the ESP)
#   Window 2: trial/cloud-dev.js     (online dashboard + API + MongoDB)
# The machine server pushes orders/alerts to the cloud with SYNC_SECRET.
# MongoDB: in-memory by default (no install), or -MongoUri for Atlas/mongod.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$serverDir = Join-Path $root "banyu"
$settingsPath = Join-Path $serverDir "settings.env"

if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  throw "Node.js 20+ is required: https://nodejs.org (check 'node --version')."
}

function Normalize-Base([string]$v) {
  $v = ($v -as [string]).Trim()
  if (-not $v) { return "" }
  if ($v -notmatch '^https?://') { $v = "http://" + $v }
  return $v.TrimEnd('/')
}
function Get-EnvValue {
  param([string[]]$Lines, [string]$Key)
  foreach ($l in $Lines) { if ($l -match "^\s*$Key\s*=\s*(.*?)\s*$") { return $matches[1] } }
  return ""
}
function Set-EnvValue {
  param([string[]]$Lines, [string]$Key, [string]$Value)
  $found = $false
  $out = New-Object System.Collections.Generic.List[string]
  foreach ($l in $Lines) {
    if ($l -match "^\s*$Key\s*=") { [void]$out.Add("$Key=$Value"); $found = $true }
    else { [void]$out.Add($l) }
  }
  if (-not $found) { [void]$out.Add("$Key=$Value") }
  return $out.ToArray()
}
function New-Secret {
  $bytes = New-Object byte[] 32
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  return (($bytes | ForEach-Object { $_.ToString("x2") }) -join "")
}

if (-not (Test-Path $settingsPath)) {
  Set-Content -Path $settingsPath -Encoding ASCII -Value @(
    "# Generated by trial/start-recipe-b.ps1 - edit and restart to change.",
    "PAYMENT_MODE=mock",
    "MIDTRANS_SERVER_KEY=",
    "MIDTRANS_ENV=sandbox",
    "MIDTRANS_PAYMENTS=",
    "ESP32_BASE_URL=$(Normalize-Base $EspIp)",
    "ADMIN_KEYWORDS=banyu123",
    "CLOUD_URL=",
    "SYNC_SECRET=",
    "MACHINE_ID=banyu-kiosk-01"
  )
  Write-Host "Created $settingsPath" -ForegroundColor Green
}

$lines = @(Get-Content $settingsPath)
$esp = Normalize-Base $EspIp
$cloudLocal = "http://localhost:$CloudPort"

# Preserve an existing non-local cloud URL unless one is passed explicitly.
$currentCloud = Get-EnvValue $lines "CLOUD_URL"
if ($CloudUrl) {
  $targetCloud = Normalize-Base $CloudUrl
} elseif (-not $currentCloud -or $currentCloud -match '^https?://localhost') {
  $targetCloud = $cloudLocal
} else {
  $targetCloud = $currentCloud
  Write-Host "Keeping existing CLOUD_URL=$currentCloud (pass -CloudUrl to change)." -ForegroundColor Yellow
}
$lines = Set-EnvValue $lines "CLOUD_URL" $targetCloud

if (-not (Get-EnvValue $lines "SYNC_SECRET")) {
  $secret = New-Secret
  $lines = Set-EnvValue $lines "SYNC_SECRET" $secret
  Write-Host "Generated a SYNC_SECRET for this trial." -ForegroundColor Green
}
if (-not (Get-EnvValue $lines "ADMIN_KEYWORDS")) { $lines = Set-EnvValue $lines "ADMIN_KEYWORDS" "banyu123" }
if ($esp -and -not (Get-EnvValue $lines "ESP32_BASE_URL")) { $lines = Set-EnvValue $lines "ESP32_BASE_URL" $esp }
Set-Content -Path $settingsPath -Value $lines -Encoding ASCII

$conf = @{}
Get-Content $settingsPath | ForEach-Object {
  if ($_ -match '^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$') { $conf[$matches[1]] = $matches[2] }
}
$keyword = if ($conf['ADMIN_KEYWORDS']) { $conf['ADMIN_KEYWORDS'].Split(',')[0].Trim() } else { 'banyu123' }
$espShown = if ($conf['ESP32_BASE_URL']) { $conf['ESP32_BASE_URL'] } else { '(empty - demo mode)' }
$payment = if ($conf['PAYMENT_MODE']) { $conf['PAYMENT_MODE'] } else { 'mock' }
$cloudShown = if ($conf['CLOUD_URL']) { $conf['CLOUD_URL'] } else { '(off)' }
$mongoShown = if ($MongoUri) { $MongoUri } else { 'in-memory (temporary)' }

$kioskUrl = "http://localhost:$KioskPort/"
$dashUrl = "http://localhost:$CloudPort/dashboard.html"
$lan = @(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
  Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' } |
  Select-Object -ExpandProperty IPAddress -Unique)

Write-Host ""
Write-Host "Banyu kiosk - Recipe B (laptop + cloud copy)" -ForegroundColor Cyan
Write-Host "  Payment mode : $payment"
Write-Host "  Dispenser    : $espShown"
Write-Host "  Cloud URL    : $cloudShown"
Write-Host "  MongoDB      : $mongoShown"
Write-Host ""
Write-Host "  Kiosk            : $kioskUrl"
Write-Host "  Online dashboard : $dashUrl"
Write-Host "  Dashboard login  : $keyword"
if ($lan.Count -gt 0) {
  Write-Host "  Tablet           : http://$($lan[0]):$KioskPort/   (same Wi-Fi)"
}
Write-Host ""
Write-Host "The cloud window downloads MongoDB on the first run - wait for 'Dashboard :'." -ForegroundColor DarkGray
Write-Host "Use -MongoUri mongodb+srv://... to keep data in Atlas instead of memory." -ForegroundColor DarkGray
Write-Host ""

if ($NoStart) {
  Write-Host "NoStart: settings and dependencies are not started." -ForegroundColor Yellow
  exit 0
}

# --- dependencies -----------------------------------------------------------
Push-Location $root
try {
  if (-not (Test-Path (Join-Path $root "node_modules\mongodb"))) {
    Write-Host "Installing cloud dependencies (mongodb)..." -ForegroundColor Cyan
    & npm.cmd install --no-audit --no-fund
  }
  Push-Location (Join-Path $root "trial")
  try {
    if (-not (Test-Path (Join-Path $root "trial\node_modules\mongodb-memory-server"))) {
      Write-Host "Installing trial MongoDB helper (first run may take a minute)..." -ForegroundColor Cyan
      & npm.cmd install --no-audit --no-fund
    }
  } finally { Pop-Location }
} finally { Pop-Location }

# --- start both halves in their own windows ---------------------------------
$env:CLOUD_PORT = "$CloudPort"
if ($MongoUri) { $env:MONGODB_URI = $MongoUri }

$cloudCmd = "Set-Location -LiteralPath '$root'; node trial/cloud-dev.js"
Start-Process powershell.exe -ArgumentList @("-NoExit", "-Command", $cloudCmd) | Out-Null

Start-Sleep -Seconds 2
$env:PORT = "$KioskPort"
$kioskCmd = "Set-Location -LiteralPath '$serverDir'; node server.js"
Start-Process powershell.exe -ArgumentList @("-NoExit", "-Command", $kioskCmd) | Out-Null

Start-Sleep -Seconds 5
Start-Process $kioskUrl | Out-Null
Start-Process $dashUrl | Out-Null

Write-Host ""
Write-Host "Started:" -ForegroundColor Green
Write-Host "  cloud window : $dashUrl  (login: $keyword)"
Write-Host "  kiosk window : $kioskUrl"
Write-Host "Close both windows to stop the trial." -ForegroundColor DarkGray
